import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
const [repo,scratch,themeName='dark']=process.argv.slice(2);
mkdirSync(join(scratch,'profile'),{recursive:true});
Object.assign(process.env,{GENTLE_PI_CONFIG_HOME:join(scratch,'profile'),GENTLE_PI_AGENT_HOME:join(scratch,'profile'),PI_CODING_AGENT_DIR:join(scratch,'profile')});
const sdkPath=join(repo,'node_modules/@earendil-works/pi-coding-agent/dist/index.js');
const sdk=await import(pathToFileURL(sdkPath).href);
const {theme}=await import(pathToFileURL(join(repo,'node_modules/@earendil-works/pi-coding-agent/dist/modes/interactive/theme/theme.js')).href);
const {TuiAltScreen,ProcessTerminal}=await import(pathToFileURL(join(repo,'node_modules/@earendil-works/pi-tui/dist/index.js')).href);
const {setCardStyle,CARD_STYLE}=await import(pathToFileURL(join(repo,'lib/shell-card.ts')).href);
const {default:install}=await import(pathToFileURL(join(repo,'extensions/gentle-todo.ts')).href);
sdk.initTheme(themeName);setCardStyle(CARD_STYLE.NEON);
const handlers=new Map(),tools=new Map();let component;
const ui=new TuiAltScreen(new ProcessTerminal());
const pi={on:(name,fn)=>handlers.set(name,[...(handlers.get(name)||[]),fn]),registerTool:tool=>tools.set(tool.name,tool),registerShortcut(){},events:{emit(){},on(){}}};
const ctx={cwd:repo,hasUI:true,sessionManager:{getSessionId:()=> 'todo-visual',getBranch:()=>[]},ui:{setWidget(_key,factory){if(factory){component=factory(ui,theme);ui.addChild(component);}},notify(){}}};
const fire=async(name,event={})=>{for(const fn of handlers.get(name)||[])await fn(event,ctx);};
install(pi,{});await fire('session_start');
await tools.get('todo').execute('write',{action:'write',tasks:[{title:'Verify ODD continuity',status:'in_progress'},{title:'Run regression checks'}]},undefined,undefined,ctx);
await fire('tool_execution_end',{toolName:'todo'});
for(let i=0;i<3;i++)await fire('before_agent_start',{messageType:'custom',message:{role:'custom',customType:'worker-complete',content:'Finished',display:false,timestamp:i},systemPrompt:'base',systemPromptOptions:{appendSystemPrompt:''}});
ui.start();ui.requestRender();writeFileSync(join(scratch,'stream-start.json'),JSON.stringify({at:Date.now(),repo,themeName}));
const stop=()=>{ui.stop();process.exit(0)};process.on('SIGTERM',stop);process.on('SIGINT',stop);setTimeout(stop,40000);
